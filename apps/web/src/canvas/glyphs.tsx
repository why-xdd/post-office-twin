  cashier_window: Mails,
  pvz_counter: PackageOpen,
  self_service_kiosk: Ticket,
  payment_terminal_stand: CreditCard,
  package_drop_box: Mailbox,
  info_display: Monitor,
  media_panel: Tv,
  waiting_seat: Armchair,
  atm: Landmark,
